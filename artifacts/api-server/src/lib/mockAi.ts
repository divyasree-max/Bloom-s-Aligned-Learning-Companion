/**
 * Extract key concepts from text (mock implementation).
 * Replace with NLP/AI call for real implementation.
 */
function extractConcepts(text: string): string[] {
  const words = text
    .replace(/[^a-zA-Z\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 5)
    .slice(0, 40);

  const unique = [...new Set(words)].slice(0, 12);
  const capitalized = unique.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase());
  return capitalized.length > 0 ? capitalized : [
    "Academic Content", "Key Principles", "Core Concepts", "Fundamental Ideas",
    "Main Theories", "Subject Matter", "Domain Knowledge"
  ];
}

